def call_api_with_id(user_id):
    try:
        conn = http.client.HTTPSConnection("ins-app-api.mmweb.top")
        payload = json.dumps({
            "id": user_id
        })
        headers = {
            'User-Agent': 'Apifox/1.0.0 (https://apifox.com)',
            'Content-Type': 'application/json',
            'Accept': '*/*',
            'Host': 'ins-app-api.mmweb.top',
            'Connection': 'keep-alive'
        }
        
        # Make the API call
        conn.request("POST", "/feign/ins-app/partner/re-calculate-partner-score", payload, headers)
        response = conn.getresponse()
        data = response.read()
        
        # Print the response for monitoring
        print(f"Called API for user_id: {user_id}")
        print(f"Status code: {response.status}")
        print(f"Response: {data.decode('utf-8')}\n")
        
        # Close the connection
        conn.close()
        
    except Exception as e:
        print(f"Error calling API for user_id {user_id}: {str(e)}\n")

